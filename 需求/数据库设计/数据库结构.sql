-- 学术服务小程序 V0.2 数据库结构建议；PostgreSQL 18 语法。
-- 仅在独立空数据库中执行。无 DROP、无生产连接、无真实业务数据。
-- 原文件为设计交付，不代表已部署。应用事务与权限合同见《数据库设计.md》。
BEGIN;

-- @table accounts 统一账号；客户、员工与系统操作者的身份根。
CREATE TABLE accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 内部主键；接口可使用业务编号避免暴露连续ID
    kind VARCHAR(12) NOT NULL CHECK (kind IN ('customer','staff','system')), -- 账号类型
    display_name VARCHAR(100), -- 可选显示名
    contact_ciphertext TEXT, -- 联系方式密文；密钥不在数据库
    status VARCHAR(12) NOT NULL DEFAULT 'active' CHECK (status IN ('active','suspended','closed')), -- 有效状态
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 创建时间
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 最近变更时间
    closed_at TIMESTAMPTZ, -- 注销时间；不级联销毁交易历史
    version INTEGER NOT NULL DEFAULT 1 CHECK (version > 0) -- 乐观锁版本
);

-- @table auth_identities 微信等认证身份；不得保存session_key、Token或明文密码。
CREATE TABLE auth_identities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 身份记录主键
    account_id BIGINT NOT NULL REFERENCES accounts(id), -- 所属账号
    provider VARCHAR(24) NOT NULL CHECK (provider IN ('wechat','staff_identity')), -- 认证来源
    app_id VARCHAR(100) NOT NULL, -- 应用标识；微信OpenID按应用隔离
    subject_ciphertext TEXT NOT NULL, -- 外部身份标识密文
    subject_hash CHAR(64) NOT NULL CHECK (subject_hash ~ '^[0-9a-f]{64}$'), -- 用于唯一匹配的受控HMAC摘要
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 绑定时间
    revoked_at TIMESTAMPTZ, -- 撤销时间
    UNIQUE (provider, app_id, subject_hash)
);
CREATE INDEX auth_identities_account_idx ON auth_identities(account_id);

-- @table staff_roles 员工角色；最小RBAC，订单数据范围还需授权校验。
CREATE TABLE staff_roles (
    account_id BIGINT NOT NULL REFERENCES accounts(id), -- 员工账号；服务端验证kind=staff
    role_code VARCHAR(20) NOT NULL CHECK (role_code IN ('admin','operator','service_agent','finance')), -- 固定最小角色
    granted_by BIGINT NOT NULL REFERENCES accounts(id), -- 授权管理员
    granted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 授权时间
    revoked_at TIMESTAMPTZ, -- 撤权时间；恢复授权更新本行并记审计
    PRIMARY KEY (account_id, role_code)
);

-- @table service_categories 固定且仅三类；修改服务范围须改需求和迁移。
CREATE TABLE service_categories (
    code VARCHAR(16) PRIMARY KEY CHECK (code IN ('graduation','journal','editing')), -- 分类业务代码
    name VARCHAR(20) NOT NULL, -- 中文名称
    sort_order INTEGER NOT NULL CHECK (sort_order > 0), -- 展示顺序
    CHECK ((code='graduation' AND name='毕业论文') OR (code='journal' AND name='普刊') OR (code='editing' AND name='编译'))
);
INSERT INTO service_categories(code,name,sort_order) VALUES
    ('graduation','毕业论文',1),('journal','普刊',2),('editing','编译',3);

-- @table service_items 子服务目录；不虚构未确认的可售菜单。
CREATE TABLE service_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 子服务主键
    category_code VARCHAR(16) NOT NULL REFERENCES service_categories(code), -- 所属固定分类
    item_code VARCHAR(60) NOT NULL UNIQUE, -- 稳定业务代码
    status VARCHAR(16) NOT NULL DEFAULT 'offline' CHECK (status IN ('offline','online','archived')), -- 上下架状态
    sort_order INTEGER NOT NULL DEFAULT 0, -- 类内排序
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 创建时间
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 最近变更时间
    UNIQUE (id, category_code)
);
CREATE INDEX service_items_category_idx ON service_items(category_code,status,sort_order);

-- @table service_item_versions 子服务发布版本；发布后内容不可原位覆盖。
CREATE TABLE service_item_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 版本主键
    service_item_id BIGINT NOT NULL REFERENCES service_items(id), -- 所属子服务
    version_no INTEGER NOT NULL CHECK (version_no > 0), -- 类内版本序号
    title VARCHAR(120) NOT NULL CHECK (length(trim(title)) > 0), -- 版本标题
    content_json JSONB NOT NULL CHECK (jsonb_typeof(content_json)='object'), -- 范围、交付、材料和规则的结构化内容
    form_schema_json JSONB NOT NULL CHECK (jsonb_typeof(form_schema_json)='object'), -- 业务表单字段及条件必填定义
    pricing_mode VARCHAR(20) NOT NULL CHECK (pricing_mode IN ('manual_quote','fixed_price')), -- 定价表达方式
    fixed_price_minor BIGINT CHECK (fixed_price_minor >= 0), -- 固定价格最小币种单位；人工报价为空
    currency CHAR(3) NOT NULL DEFAULT 'CNY' CHECK (currency ~ '^[A-Z]{3}$'), -- 币种
    published_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 发布时间
    published_by BIGINT NOT NULL REFERENCES accounts(id), -- 发布员工
    UNIQUE (service_item_id,version_no),
    UNIQUE (id,service_item_id),
    CHECK ((pricing_mode='fixed_price' AND fixed_price_minor IS NOT NULL) OR (pricing_mode='manual_quote' AND fixed_price_minor IS NULL))
);

-- @table policy_versions 协议、隐私和服务规则的不可变发布版本。
CREATE TABLE policy_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 文本版本主键
    policy_code VARCHAR(60) NOT NULL, -- privacy、terms、service_rules等稳定代码
    version_no INTEGER NOT NULL CHECK (version_no > 0), -- 文本版本序号
    content_text TEXT NOT NULL CHECK (length(trim(content_text)) > 0), -- 真实发布正文
    content_hash CHAR(64) NOT NULL CHECK (content_hash ~ '^[0-9a-f]{64}$'), -- 发布正文SHA-256
    published_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 发布时间
    published_by BIGINT NOT NULL REFERENCES accounts(id), -- 发布人员
    UNIQUE (policy_code,version_no)
);

-- @table user_consents 用户对指定文本版本的授权或撤回事件。
CREATE TABLE user_consents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 事件主键
    account_id BIGINT NOT NULL REFERENCES accounts(id), -- 操作用户
    policy_version_id BIGINT NOT NULL REFERENCES policy_versions(id), -- 看到的真实版本
    action VARCHAR(12) NOT NULL CHECK (action IN ('accepted','revoked')), -- 授权或撤回
    purpose_code VARCHAR(60) NOT NULL, -- 对应信息处理用途
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 事件时间
    client_request_id VARCHAR(100) NOT NULL, -- 防重复事件标识
    UNIQUE (account_id,client_request_id)
);
CREATE INDEX user_consents_lookup_idx ON user_consents(account_id,purpose_code,occurred_at DESC);

-- @table service_requests 需求单主记录；主行锁串行化补材料、重报价与接受报价。
CREATE TABLE service_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 需求主键
    request_no VARCHAR(40) NOT NULL UNIQUE, -- 面向用户的不可猜测业务编号
    owner_id BIGINT NOT NULL REFERENCES accounts(id), -- 客户账号
    submit_key VARCHAR(120) NOT NULL, -- 客户端稳定提交键，幂等缓存清理后仍可查原需求
    submit_hash CHAR(64) NOT NULL CHECK (submit_hash ~ '^[0-9a-f]{64}$'), -- 首次提交正文规范化摘要，同键异摘要由服务拒绝
    category_code VARCHAR(16) NOT NULL REFERENCES service_categories(code), -- 固定服务分类
    service_item_id BIGINT, -- 可选子服务；只选大类也能咨询
    status VARCHAR(24) NOT NULL DEFAULT 'pending_review' CHECK (status IN ('pending_review','awaiting_material','awaiting_quote_accept','converted','closed')), -- 需求状态
    current_quote_id BIGINT, -- 当前对用户有效的报价版本；外键在报价表后补充
    assigned_staff_id BIGINT REFERENCES accounts(id), -- 转单前负责客服；转单后按订单授权
    close_reason TEXT, -- 关闭原因
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 提交时间
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 更新时间
    closed_at TIMESTAMPTZ, -- 关闭时间
    version INTEGER NOT NULL DEFAULT 1 CHECK (version > 0), -- 并发更新版本
    UNIQUE (id,owner_id),
    UNIQUE (id,owner_id,category_code),
    UNIQUE (owner_id,submit_key),
    FOREIGN KEY (service_item_id,category_code) REFERENCES service_items(id,category_code),
    CHECK (status <> 'closed' OR (closed_at IS NOT NULL AND close_reason IS NOT NULL AND length(trim(close_reason)) > 0))
);
CREATE INDEX service_requests_owner_idx ON service_requests(owner_id,created_at DESC);
CREATE INDEX service_requests_work_idx ON service_requests(assigned_staff_id,status,updated_at);

-- @table request_revisions 每次正式提交或补充形成新版本，不覆盖原始需求。
CREATE TABLE request_revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 材料版本主键
    request_id BIGINT NOT NULL, -- 所属需求
    owner_id BIGINT NOT NULL, -- 客户账号；冗余字段用于复合外键隔离
    revision_no INTEGER NOT NULL CHECK (revision_no > 0), -- 版本序号
    schema_version INTEGER NOT NULL CHECK (schema_version > 0), -- 本次JSON字段协议版本
    service_item_id BIGINT, -- 大类咨询可空；选择子服务时记录当时子服务
    service_item_version_id BIGINT, -- 与子服务同时存在的发布版本
    form_json JSONB NOT NULL CHECK (jsonb_typeof(form_json)='object'), -- 三类表单的结构化快照
    summary TEXT NOT NULL CHECK (length(trim(summary)) > 0), -- 本次需求说明
    desired_date DATE, -- 希望完成日期；不是交付承诺
    created_by BIGINT NOT NULL REFERENCES accounts(id), -- 提交者或经授权代录员工
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 提交时间
    FOREIGN KEY (request_id,owner_id) REFERENCES service_requests(id,owner_id),
    FOREIGN KEY (service_item_version_id,service_item_id) REFERENCES service_item_versions(id,service_item_id),
    CHECK ((service_item_id IS NULL AND service_item_version_id IS NULL) OR (service_item_id IS NOT NULL AND service_item_version_id IS NOT NULL)),
    UNIQUE (request_id,revision_no),
    UNIQUE (id,request_id,owner_id)
);

-- @table quote_versions 完整报价发布版本；旧版、过期和并发接受由事务核验。
CREATE TABLE quote_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 报价版本主键
    request_id BIGINT NOT NULL, -- 所属需求
    owner_id BIGINT NOT NULL, -- 客户账号
    request_revision_id BIGINT NOT NULL, -- 报价评估使用的材料版本
    category_code VARCHAR(16) NOT NULL, -- 正式报价所属固定分类，必须匹配需求和子服务
    service_item_id BIGINT NOT NULL, -- 正式报价必须选择本方真实子服务
    service_item_version_id BIGINT NOT NULL, -- 固定发布版本，快照中保留该引用
    version_no INTEGER NOT NULL CHECK (version_no > 0), -- 需求内报价序号
    status VARCHAR(16) NOT NULL DEFAULT 'offered' CHECK (status IN ('offered','superseded','accepted','declined','expired')), -- 报价生命周期
    total_minor BIGINT NOT NULL CHECK (total_minor >= 0), -- 用户向平台应付总额；外部直接收费不计入
    currency CHAR(3) NOT NULL DEFAULT 'CNY' CHECK (currency ~ '^[A-Z]{3}$'), -- 币种
    start_required_minor BIGINT NOT NULL CHECK (start_required_minor >= 0 AND start_required_minor <= total_minor), -- 启动所需已核实收款阈值，可为零
    terms_json JSONB NOT NULL CHECK (jsonb_typeof(terms_json)='object'), -- 范围、排除、交付、周期、修改、取消退款及付款安排
    policy_version_id BIGINT NOT NULL REFERENCES policy_versions(id), -- 报价适用服务规则版本
    content_hash CHAR(64) NOT NULL CHECK (content_hash ~ '^[0-9a-f]{64}$'), -- 完整报价及费用行规范化哈希
    valid_until TIMESTAMPTZ NOT NULL, -- 接受截止时刻；不使用now()做跨时间CHECK
    created_by BIGINT NOT NULL REFERENCES accounts(id), -- 报价发布者
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 发布时间
    FOREIGN KEY (request_id,owner_id) REFERENCES service_requests(id,owner_id),
    FOREIGN KEY (request_id,owner_id,category_code) REFERENCES service_requests(id,owner_id,category_code),
    FOREIGN KEY (service_item_id,category_code) REFERENCES service_items(id,category_code),
    FOREIGN KEY (service_item_version_id,service_item_id) REFERENCES service_item_versions(id,service_item_id),
    FOREIGN KEY (request_revision_id,request_id,owner_id) REFERENCES request_revisions(id,request_id,owner_id),
    UNIQUE (request_id,version_no),
    UNIQUE (id,request_id),
    UNIQUE (id,request_id,owner_id,currency),
    CHECK (valid_until > created_at)
);
CREATE UNIQUE INDEX quote_versions_one_offered_idx ON quote_versions(request_id) WHERE status='offered';
ALTER TABLE service_requests ADD CONSTRAINT service_requests_quote_fk FOREIGN KEY (current_quote_id,id) REFERENCES quote_versions(id,request_id);

-- @table quote_lines 费用明细；平台收费与第三方直接收费明确分列。
CREATE TABLE quote_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 明细主键
    quote_id BIGINT NOT NULL REFERENCES quote_versions(id), -- 报价版本
    line_no INTEGER NOT NULL CHECK (line_no > 0), -- 明细序号
    description TEXT NOT NULL CHECK (length(trim(description)) > 0), -- 费用说明
    payee_kind VARCHAR(16) NOT NULL CHECK (payee_kind IN ('platform','third_party')), -- 收款方类型
    included_in_total BOOLEAN NOT NULL, -- 是否包含在平台应付总额
    amount_minor BIGINT NOT NULL CHECK (amount_minor >= 0), -- 同报价币种最小单位金额
    payee_note TEXT, -- 第三方名称及缴费方式说明，不含账户秘密
    UNIQUE (quote_id,line_no),
    CHECK (NOT included_in_total OR payee_kind='platform')
);

-- @table quote_acceptances 接受凭证；一需求只允许一次正式接受并转一订单。
CREATE TABLE quote_acceptances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 确认主键
    request_id BIGINT NOT NULL UNIQUE, -- 一需求只转一单
    owner_id BIGINT NOT NULL, -- 必须为需求本人
    quote_id BIGINT NOT NULL UNIQUE, -- 被接受报价版本
    currency CHAR(3) NOT NULL CHECK (currency ~ '^[A-Z]{3}$'), -- 冻结币种
    quote_hash CHAR(64) NOT NULL CHECK (quote_hash ~ '^[0-9a-f]{64}$'), -- 客户确认时看到的完整报价哈希
    accepted_snapshot JSONB NOT NULL CHECK (jsonb_typeof(accepted_snapshot)='object'), -- 全报价、费用行、规则和材料版本快照
    accepted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 服务端确认时间
    FOREIGN KEY (quote_id,request_id,owner_id,currency) REFERENCES quote_versions(id,request_id,owner_id,currency),
    UNIQUE (id,request_id,owner_id,currency)
);

-- @table service_orders 服务订单；支付尝试关闭不改变服务订单取消状态。
CREATE TABLE service_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 订单主键
    order_no VARCHAR(40) NOT NULL UNIQUE, -- 面向用户业务编号
    request_id BIGINT NOT NULL UNIQUE, -- 唯一来源需求
    owner_id BIGINT NOT NULL, -- 客户账号
    acceptance_id BIGINT NOT NULL UNIQUE, -- 唯一报价确认凭证
    currency CHAR(3) NOT NULL CHECK (currency ~ '^[A-Z]{3}$'), -- 订单币种，收款后不可变更
    total_minor BIGINT NOT NULL CHECK (total_minor >= 0), -- 当前有效平台应付总额
    start_required_minor BIGINT NOT NULL CHECK (start_required_minor >= 0 AND start_required_minor <= total_minor), -- 当前有效启动收款阈值
    initial_terms_json JSONB NOT NULL CHECK (jsonb_typeof(initial_terms_json)='object'), -- 原始成交快照，禁止覆盖
    effective_terms_json JSONB NOT NULL CHECK (jsonb_typeof(effective_terms_json)='object'), -- 当前有效条款；经确认变更后事务更新
    status VARCHAR(24) NOT NULL DEFAULT 'pending_start' CHECK (status IN ('pending_start','in_service','awaiting_acceptance','revising','completed','cancelled')), -- 服务状态
    material_ready BOOLEAN NOT NULL DEFAULT FALSE, -- 材料是否齐备；由服务端核验
    scheduled_at TIMESTAMPTZ, -- 排期确认时刻
    started_at TIMESTAMPTZ, -- 实际启动时刻
    due_at TIMESTAMPTZ, -- 双方约定的到期时刻
    completed_at TIMESTAMPTZ, -- 主服务完成时刻；售后不抹除
    cancelled_at TIMESTAMPTZ, -- 取消生效时刻
    current_change_id BIGINT, -- 当前生效变更版本，外键后补
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 建单时间
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 更新时间
    version INTEGER NOT NULL DEFAULT 1 CHECK (version > 0), -- 状态及条款乐观锁
    FOREIGN KEY (acceptance_id,request_id,owner_id,currency) REFERENCES quote_acceptances(id,request_id,owner_id,currency),
    UNIQUE (id,request_id,owner_id),
    UNIQUE (id,owner_id),
    UNIQUE (id,currency),
    CHECK (status <> 'completed' OR completed_at IS NOT NULL),
    CHECK (status <> 'cancelled' OR cancelled_at IS NOT NULL)
);
CREATE INDEX service_orders_owner_idx ON service_orders(owner_id,created_at DESC);
CREATE INDEX service_orders_status_due_idx ON service_orders(status,due_at);

-- @table order_assignments 员工按订单授权；撤回即失去材料访问权。
CREATE TABLE order_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 分配记录主键
    order_id BIGINT NOT NULL REFERENCES service_orders(id), -- 授权订单
    staff_id BIGINT NOT NULL REFERENCES accounts(id), -- 员工账号
    scope_code VARCHAR(20) NOT NULL CHECK (scope_code IN ('case_manage','service_files','finance')), -- 订单内数据及操作范围
    assigned_by BIGINT NOT NULL REFERENCES accounts(id), -- 授权者
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 授权时间
    revoked_at TIMESTAMPTZ -- 撤回时间；不删除历史
);
CREATE UNIQUE INDEX order_assignments_active_idx ON order_assignments(order_id,staff_id,scope_code) WHERE revoked_at IS NULL;
CREATE INDEX order_assignments_staff_idx ON order_assignments(staff_id,revoked_at);

-- @table order_change_versions 订单范围和交期变更提案；接受后才生效。
CREATE TABLE order_change_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 变更主键
    order_id BIGINT NOT NULL REFERENCES service_orders(id), -- 所属订单
    version_no INTEGER NOT NULL CHECK (version_no > 0), -- 订单内变更序号
    based_on_order_version INTEGER NOT NULL CHECK (based_on_order_version > 0), -- 提案基于订单版本
    status VARCHAR(16) NOT NULL DEFAULT 'proposed' CHECK (status IN ('proposed','accepted','rejected','expired')), -- 提案状态
    reason TEXT NOT NULL, -- 变更原因
    proposed_terms_json JSONB NOT NULL CHECK (jsonb_typeof(proposed_terms_json)='object'), -- 变更后的完整条款及费用快照
    total_minor BIGINT NOT NULL CHECK (total_minor >= 0), -- 新平台应付总额
    start_required_minor BIGINT NOT NULL CHECK (start_required_minor >= 0 AND start_required_minor <= total_minor), -- 新启动阈值
    due_at TIMESTAMPTZ, -- 新交期
    proposed_by BIGINT NOT NULL REFERENCES accounts(id), -- 提案人员
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 提案时间
    valid_until TIMESTAMPTZ NOT NULL, -- 确认有效期
    accepted_by BIGINT REFERENCES accounts(id), -- 实际确认客户；应用验证是订单本人
    accepted_at TIMESTAMPTZ, -- 确认时间
    UNIQUE (order_id,version_no),
    UNIQUE (id,order_id),
    FOREIGN KEY (order_id,accepted_by) REFERENCES service_orders(id,owner_id),
    CHECK (valid_until > created_at),
    CHECK (status <> 'accepted' OR (accepted_by IS NOT NULL AND accepted_at IS NOT NULL))
);
ALTER TABLE service_orders ADD CONSTRAINT service_orders_change_fk FOREIGN KEY (current_change_id,id) REFERENCES order_change_versions(id,order_id);

-- @table attachments 私有对象存储元数据；文件内容不存数据库。
CREATE TABLE attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 文件版本主键
    request_id BIGINT, -- 暂存上传可为空；绑定业务前必须归属需求
    owner_id BIGINT NOT NULL REFERENCES accounts(id), -- 业务客户，非上传员工
    uploaded_by BIGINT NOT NULL REFERENCES accounts(id), -- 实际上传者
    storage_key TEXT NOT NULL UNIQUE, -- 私有存储对象键，不是公开URL
    original_name VARCHAR(255) NOT NULL, -- 原始文件名，展示前转义
    media_type VARCHAR(120) NOT NULL, -- 实测文件媒体类型
    byte_size BIGINT NOT NULL CHECK (byte_size > 0), -- 文件大小
    sha256 CHAR(64) NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'), -- 内容摘要
    status VARCHAR(20) NOT NULL DEFAULT 'staging' CHECK (status IN ('staging','available','quarantined','pending_delete','deleted')), -- 上传、扫描和删除状态
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 上传时间
    expires_at TIMESTAMPTZ, -- 依确认的保留策略生成失效时刻
    deleted_at TIMESTAMPTZ, -- 物理对象删除完成时间
    FOREIGN KEY (request_id,owner_id) REFERENCES service_requests(id,owner_id),
    UNIQUE (id,request_id,owner_id),
    CHECK (status <> 'deleted' OR deleted_at IS NOT NULL)
);
CREATE INDEX attachments_owner_status_idx ON attachments(owner_id,status,created_at);
CREATE INDEX attachments_expiry_idx ON attachments(expires_at) WHERE status IN ('staging','pending_delete');

-- @table after_sales 售后任务；服务状态和资金执行各自记录。
CREATE TABLE after_sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 售后主键
    after_sale_no VARCHAR(40) NOT NULL UNIQUE, -- 用户可查业务编号
    order_id BIGINT NOT NULL, -- 关联订单
    request_id BIGINT NOT NULL, -- 关联来源需求
    owner_id BIGINT NOT NULL, -- 申请客户
    kind VARCHAR(20) NOT NULL CHECK (kind IN ('cancel','revision','refund','dispute')), -- 申请类型
    reason TEXT NOT NULL CHECK (length(trim(reason)) > 0), -- 申请原因
    status VARCHAR(16) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','processing','resolved','closed')), -- 处理状态
    resolution_json JSONB, -- 处理范围、结论和执行条件，不含原稿正文
    assigned_staff_id BIGINT REFERENCES accounts(id), -- 处理负责人
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 申请时间
    resolved_at TIMESTAMPTZ, -- 实际解决时间
    version INTEGER NOT NULL DEFAULT 1 CHECK (version > 0), -- 并发更新版本
    FOREIGN KEY (order_id,request_id,owner_id) REFERENCES service_orders(id,request_id,owner_id),
    UNIQUE (id,order_id),
    UNIQUE (id,request_id,owner_id),
    CHECK (status <> 'resolved' OR (resolved_at IS NOT NULL AND resolution_json IS NOT NULL)),
    CHECK (resolution_json IS NULL OR jsonb_typeof(resolution_json)='object')
);
CREATE INDEX after_sales_work_idx ON after_sales(assigned_staff_id,status,created_at);

-- @table deliveries 交付批次；完成后的修订必须归属售后任务。
CREATE TABLE deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 交付主键
    order_id BIGINT NOT NULL, -- 所属订单
    request_id BIGINT NOT NULL, -- 来源需求
    owner_id BIGINT NOT NULL, -- 客户
    delivery_no INTEGER NOT NULL CHECK (delivery_no > 0), -- 订单内版本序号
    kind VARCHAR(16) NOT NULL CHECK (kind IN ('main','after_sale')), -- 主服务或售后交付
    after_sale_id BIGINT, -- 售后交付必须关联任务
    status VARCHAR(20) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','released','accepted','needs_revision')), -- 交付状态
    release_note TEXT NOT NULL, -- 本次交付说明
    created_by BIGINT NOT NULL REFERENCES accounts(id), -- 交付人员
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 建立版本时间
    released_at TIMESTAMPTZ, -- 正式交付时间；正式交付后文件及说明不可原位改写
    FOREIGN KEY (order_id,request_id,owner_id) REFERENCES service_orders(id,request_id,owner_id),
    FOREIGN KEY (after_sale_id,order_id) REFERENCES after_sales(id,order_id),
    UNIQUE (order_id,delivery_no),
    UNIQUE (id,order_id),
    UNIQUE (id,request_id,owner_id),
    CHECK ((kind='main' AND after_sale_id IS NULL) OR (kind='after_sale' AND after_sale_id IS NOT NULL)),
    CHECK (status='draft' OR released_at IS NOT NULL)
);

-- @table attachment_links 附件归属；三种受控宿主，不采用无外键的任意多态ID。
CREATE TABLE attachment_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 绑定主键
    attachment_id BIGINT NOT NULL, -- 文件版本
    request_id BIGINT NOT NULL, -- 业务需求
    owner_id BIGINT NOT NULL, -- 业务客户
    request_revision_id BIGINT, -- 需求材料宿主
    delivery_id BIGINT, -- 交付版本宿主
    after_sale_id BIGINT, -- 售后证据宿主
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 绑定时间
    FOREIGN KEY (attachment_id,request_id,owner_id) REFERENCES attachments(id,request_id,owner_id),
    FOREIGN KEY (request_revision_id,request_id,owner_id) REFERENCES request_revisions(id,request_id,owner_id),
    FOREIGN KEY (delivery_id,request_id,owner_id) REFERENCES deliveries(id,request_id,owner_id),
    FOREIGN KEY (after_sale_id,request_id,owner_id) REFERENCES after_sales(id,request_id,owner_id),
    CHECK (num_nonnulls(request_revision_id,delivery_id,after_sale_id)=1)
);
CREATE UNIQUE INDEX attachment_links_revision_uq ON attachment_links(request_revision_id,attachment_id) WHERE request_revision_id IS NOT NULL;
CREATE UNIQUE INDEX attachment_links_delivery_uq ON attachment_links(delivery_id,attachment_id) WHERE delivery_id IS NOT NULL;
CREATE UNIQUE INDEX attachment_links_after_sale_uq ON attachment_links(after_sale_id,attachment_id) WHERE after_sale_id IS NOT NULL;
CREATE INDEX attachment_links_attachment_idx ON attachment_links(attachment_id);

-- @table delivery_feedback 客户对具体交付版本的反馈；验收和修改请求均保留事件。
CREATE TABLE delivery_feedback (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 反馈主键
    order_id BIGINT NOT NULL, -- 所属订单
    delivery_id BIGINT NOT NULL, -- 对应交付版本
    author_id BIGINT NOT NULL, -- 必须是订单本人
    action VARCHAR(20) NOT NULL CHECK (action IN ('accept','request_revision')), -- 验收或修改请求
    comment_text TEXT, -- 修改描述或验收说明
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 反馈时间
    client_request_id VARCHAR(100) NOT NULL, -- 防重复反馈标识
    FOREIGN KEY (order_id,author_id) REFERENCES service_orders(id,owner_id),
    FOREIGN KEY (delivery_id,order_id) REFERENCES deliveries(id,order_id),
    UNIQUE (author_id,client_request_id),
    CHECK (action <> 'request_revision' OR (comment_text IS NOT NULL AND length(trim(comment_text)) > 0))
);

-- @table journal_updates 普刊外部反馈；不能由内部服务状态自动推导。
CREATE TABLE journal_updates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 外部反馈主键
    order_id BIGINT NOT NULL REFERENCES service_orders(id), -- 所属普刊订单；分类由服务端核验
    status_label VARCHAR(100) NOT NULL, -- 实际外部反馈描述
    source_note TEXT NOT NULL CHECK (length(trim(source_note)) > 0), -- 来源说明
    occurred_at TIMESTAMPTZ NOT NULL, -- 外部反馈发生时刻
    recorded_by BIGINT NOT NULL REFERENCES accounts(id), -- 记录人员
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 录入时间
    correction_of_id BIGINT, -- 更正时指向同订单原记录，不覆盖旧证据
    UNIQUE (id,order_id),
    FOREIGN KEY (correction_of_id,order_id) REFERENCES journal_updates(id,order_id),
    CHECK (correction_of_id IS NULL OR correction_of_id <> id)
);
CREATE INDEX journal_updates_order_idx ON journal_updates(order_id,occurred_at DESC);

-- @table payment_records 单次收款意图或人工核验；一服务单可有多次尝试与分期。
CREATE TABLE payment_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 收款记录主键
    payment_no VARCHAR(60) NOT NULL UNIQUE, -- 平台收款业务号
    order_id BIGINT NOT NULL, -- 所属服务订单
    request_id BIGINT NOT NULL, -- 来源需求
    owner_id BIGINT NOT NULL, -- 客户
    provider VARCHAR(16) NOT NULL CHECK (provider IN ('manual','wechat')), -- A人工或B在线渠道
    merchant_scope VARCHAR(100) NOT NULL, -- 核验机构或商户作用域；不含密钥
    provider_transaction_id VARCHAR(120), -- 在线渠道交易号或人工核验的真实到账参考号，不使用图片摘要代替
    currency CHAR(3) NOT NULL CHECK (currency ~ '^[A-Z]{3}$'), -- 必须匹配订单币种
    amount_minor BIGINT NOT NULL CHECK (amount_minor > 0), -- 本次拟收／实际核验金额
    status VARCHAR(24) NOT NULL CHECK (status IN ('pending_verification','pending','succeeded','failed','closed','unknown')), -- 单次收款状态；unknown须查证
    verified_by BIGINT REFERENCES accounts(id), -- 人工核验财务人员
    evidence_attachment_id BIGINT, -- 人工到账证据元数据
    succeeded_at TIMESTAMPTZ, -- 真实到账确认时刻
    closed_at TIMESTAMPTZ, -- 本次支付尝试关闭时间，不等于服务单取消
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 建立时间
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 更新时间
    version INTEGER NOT NULL DEFAULT 1 CHECK (version > 0), -- 并发处理版本
    FOREIGN KEY (order_id,request_id,owner_id) REFERENCES service_orders(id,request_id,owner_id),
    FOREIGN KEY (order_id,currency) REFERENCES service_orders(id,currency),
    FOREIGN KEY (evidence_attachment_id,request_id,owner_id) REFERENCES attachments(id,request_id,owner_id),
    UNIQUE (id,order_id,currency),
    UNIQUE (id,provider,merchant_scope),
    UNIQUE (provider,merchant_scope,provider_transaction_id),
    CHECK (status <> 'succeeded' OR succeeded_at IS NOT NULL),
    CHECK (provider <> 'manual' OR status <> 'succeeded' OR (verified_by IS NOT NULL AND evidence_attachment_id IS NOT NULL)),
    CHECK (status <> 'succeeded' OR (provider_transaction_id IS NOT NULL AND length(trim(provider_transaction_id)) > 0))
);
CREATE INDEX payment_records_order_idx ON payment_records(order_id,status,created_at);

-- @table refund_requests 退款审批与实际执行；占额合计必须在收款行锁下计算。
CREATE TABLE refund_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 退款主键
    refund_no VARCHAR(60) NOT NULL UNIQUE, -- 平台退款业务号，重试复用
    payment_id BIGINT NOT NULL, -- 指向真实原收款
    order_id BIGINT NOT NULL, -- 所属服务订单
    after_sale_id BIGINT NOT NULL, -- 对应售后任务
    provider VARCHAR(16) NOT NULL CHECK (provider IN ('manual','wechat')), -- 必须继承原收款渠道
    merchant_scope VARCHAR(100) NOT NULL, -- 必须继承原收款核验机构或商户作用域
    currency CHAR(3) NOT NULL CHECK (currency ~ '^[A-Z]{3}$'), -- 与原收款一致
    amount_minor BIGINT NOT NULL CHECK (amount_minor > 0), -- 申请退款额
    status VARCHAR(16) NOT NULL DEFAULT 'requested' CHECK (status IN ('requested','approved','processing','unknown','succeeded','rejected','failed','cancelled')), -- 退款流程状态
    reason TEXT NOT NULL, -- 退款依据
    provider_refund_id VARCHAR(120), -- 渠道退款号或人工核实的真实退款参考号
    approved_by BIGINT REFERENCES accounts(id), -- 审批人员
    approved_at TIMESTAMPTZ, -- 审批时刻
    executed_by BIGINT REFERENCES accounts(id), -- 人工退款执行核验者
    result_note TEXT, -- 脱敏结果或人工退款凭据说明
    succeeded_at TIMESTAMPTZ, -- 退款到账确认时间
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 建立时间
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 更新时间
    version INTEGER NOT NULL DEFAULT 1 CHECK (version > 0), -- 并发更新版本
    FOREIGN KEY (payment_id,order_id,currency) REFERENCES payment_records(id,order_id,currency),
    FOREIGN KEY (payment_id,provider,merchant_scope) REFERENCES payment_records(id,provider,merchant_scope),
    FOREIGN KEY (after_sale_id,order_id) REFERENCES after_sales(id,order_id),
    UNIQUE (id,provider,merchant_scope),
    UNIQUE (provider,merchant_scope,provider_refund_id),
    CHECK (status NOT IN ('approved','processing','unknown','succeeded') OR (approved_by IS NOT NULL AND approved_at IS NOT NULL)),
    CHECK (status <> 'succeeded' OR (succeeded_at IS NOT NULL AND result_note IS NOT NULL AND length(trim(result_note)) > 0 AND provider_refund_id IS NOT NULL AND length(trim(provider_refund_id)) > 0)),
    CHECK (provider <> 'manual' OR status <> 'succeeded' OR executed_by IS NOT NULL)
);
CREATE INDEX refund_requests_payment_idx ON refund_requests(payment_id,status);
CREATE INDEX refund_requests_after_sale_idx ON refund_requests(after_sale_id);

-- @table provider_events 渠道回调幂等及处理记录；保留脱敏摘要，不保留认证秘密。
CREATE TABLE provider_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 回调记录主键
    provider VARCHAR(16) NOT NULL CHECK (provider='wechat'), -- 已设计的在线渠道
    merchant_scope VARCHAR(100) NOT NULL, -- 商户作用域
    event_key VARCHAR(160) NOT NULL, -- 渠道事件唯一标识
    payment_id BIGINT REFERENCES payment_records(id), -- 收款事件目标
    refund_id BIGINT REFERENCES refund_requests(id), -- 退款事件目标
    body_hash CHAR(64) NOT NULL CHECK (body_hash ~ '^[0-9a-f]{64}$'), -- 原消息规范化摘要，用于冲突诊断
    verified BOOLEAN NOT NULL DEFAULT FALSE, -- 已完成渠道验签及业务核验
    safe_summary JSONB NOT NULL CHECK (jsonb_typeof(safe_summary)='object'), -- 最小脱敏摘要
    state VARCHAR(16) NOT NULL DEFAULT 'received' CHECK (state IN ('received','processed','rejected','retry')), -- 处理状态
    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 收到时刻
    processed_at TIMESTAMPTZ, -- 已落账时刻
    FOREIGN KEY (payment_id,provider,merchant_scope) REFERENCES payment_records(id,provider,merchant_scope),
    FOREIGN KEY (refund_id,provider,merchant_scope) REFERENCES refund_requests(id,provider,merchant_scope),
    UNIQUE (provider,merchant_scope,event_key),
    CHECK (num_nonnulls(payment_id,refund_id)=1),
    CHECK (state <> 'processed' OR (verified AND processed_at IS NOT NULL))
);

-- @table case_events 需求、订单和售后业务事件；与状态更新在同一事务追加。
CREATE TABLE case_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 事件主键
    request_id BIGINT NOT NULL, -- 来源需求
    owner_id BIGINT NOT NULL, -- 客户账号
    order_id BIGINT, -- 可选订单；报价前事件为空
    after_sale_id BIGINT, -- 可选售后任务
    event_type VARCHAR(80) NOT NULL, -- 例如quote.accepted或order.started
    from_state VARCHAR(30), -- 变更前状态
    to_state VARCHAR(30), -- 变更后状态
    actor_id BIGINT NOT NULL REFERENCES accounts(id), -- 客户、员工或系统操作者
    visible_to_customer BOOLEAN NOT NULL DEFAULT FALSE, -- 是否可在用户进度中展示
    safe_detail JSONB NOT NULL DEFAULT '{}'::JSONB CHECK (jsonb_typeof(safe_detail)='object'), -- 脱敏事件详情
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 事件时刻
    FOREIGN KEY (request_id,owner_id) REFERENCES service_requests(id,owner_id),
    FOREIGN KEY (order_id,request_id,owner_id) REFERENCES service_orders(id,request_id,owner_id),
    FOREIGN KEY (after_sale_id,order_id) REFERENCES after_sales(id,order_id),
    CHECK (after_sale_id IS NULL OR order_id IS NOT NULL)
);
CREATE INDEX case_events_request_idx ON case_events(request_id,occurred_at,id);
CREATE INDEX case_events_order_idx ON case_events(order_id,occurred_at,id);

-- @table notification_outbox 通知待发记录；与业务事件同事务创建，重试不重放业务。
CREATE TABLE notification_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 待发主键
    event_id BIGINT NOT NULL REFERENCES case_events(id), -- 已提交的业务事件
    recipient_id BIGINT NOT NULL REFERENCES accounts(id), -- 经业务授权的接收账号
    channel VARCHAR(24) NOT NULL CHECK (channel IN ('in_app','wechat_subscription')), -- 站内或经开通授权的订阅消息
    status VARCHAR(16) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','delivering','sent','retry','dead','cancelled')), -- 投递状态
    safe_payload JSONB NOT NULL DEFAULT '{}'::JSONB CHECK (jsonb_typeof(safe_payload)='object'), -- 必要业务编号与通知模板参数，不含稿件和秘密
    attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0), -- 已尝试次数
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 下次允许执行时刻
    lease_until TIMESTAMPTZ, -- 工作器租约，避免同时领取同一任务
    last_error_code VARCHAR(100), -- 脱敏失败代码
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 登记时刻
    sent_at TIMESTAMPTZ, -- 渠道确认发送成功的时刻
    UNIQUE (event_id,recipient_id,channel),
    CHECK (status <> 'sent' OR sent_at IS NOT NULL),
    CHECK (status <> 'delivering' OR lease_until IS NOT NULL)
);
CREATE INDEX notification_outbox_due_idx ON notification_outbox(status,next_attempt_at) WHERE status IN ('pending','retry','delivering');

-- @table idempotency_records 写操作幂等；绑定身份、动作、请求摘要，不能跨用户复用结果。
CREATE TABLE idempotency_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 幂等记录主键
    actor_id BIGINT NOT NULL REFERENCES accounts(id), -- 已认证操作者
    operation VARCHAR(80) NOT NULL, -- 业务动作
    idempotency_key VARCHAR(120) NOT NULL, -- 客户端请求标识
    request_hash CHAR(64) NOT NULL CHECK (request_hash ~ '^[0-9a-f]{64}$'), -- 规范化请求摘要
    status VARCHAR(16) NOT NULL DEFAULT 'processing' CHECK (status IN ('processing','completed','failed')), -- 处理状态
    result_reference JSONB, -- 业务编号及安全响应摘要；不含文件临时链接
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 建立时间
    expires_at TIMESTAMPTZ NOT NULL, -- 按确认策略清理，不影响业务唯一约束
    UNIQUE (actor_id,operation,idempotency_key),
    CHECK (expires_at > created_at),
    CHECK (result_reference IS NULL OR jsonb_typeof(result_reference)='object')
);
CREATE INDEX idempotency_records_expiry_idx ON idempotency_records(expires_at);

-- @table audit_logs 员工与系统敏感操作审计；不记录稿件正文、令牌和完整联系方式。
CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 审计主键
    actor_id BIGINT NOT NULL REFERENCES accounts(id), -- 操作者
    action VARCHAR(100) NOT NULL, -- 操作名称
    target_type VARCHAR(60) NOT NULL, -- 目标表或受控对象类型
    target_id VARCHAR(100) NOT NULL, -- 目标业务标识；诊断引用，不宣称具有多态外键
    correlation_id VARCHAR(100) NOT NULL, -- 一次业务调用关联标识
    safe_before JSONB, -- 变更前必要脱敏字段
    safe_after JSONB, -- 变更后必要脱敏字段
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP -- 服务端时间
);
CREATE INDEX audit_logs_target_idx ON audit_logs(target_type,target_id,occurred_at);
CREATE INDEX audit_logs_actor_idx ON audit_logs(actor_id,occurred_at);

