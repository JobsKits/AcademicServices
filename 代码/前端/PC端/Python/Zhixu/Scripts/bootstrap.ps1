    Read-JobsEnterChoiceHost '请保留错误与日志，回车关闭'
    exit 1
}

# END JOBS_TERMINAL_STYLE_ORIGINAL_BODY
} finally {
    Stop-JobsTerminalStyle $__jobsTerminalStyleState
}
